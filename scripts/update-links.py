#!/usr/bin/env python3
"""Rebuild root LINKS.md from tracked Markdown and local docs; no network calls."""
from pathlib import Path
import re
import subprocess
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
EXTRA = {
    "https://github.com/HuginnsHammer/CloudSentry",
    "https://github.com/jephersonRD/PC-Free",
    "https://github.com/dockur/windows",
    "https://github.com/TechxArtisanStudio/Openterface_KVM-GO_Hardware",
    "https://github.com/9elements/VMBoot",
    "https://github.com/qemu/qemu",
    "https://www.linux-kvm.org/",
    "https://github.com/stefanberger/swtpm",
    "https://github.com/tianocore/edk2",
    "https://github.com/openbmc/openbmc",
    "https://github.com/openbmc",
    "https://github.com/topics/virtual-machine",
    "https://www.promptinjectiondatabase.com/",
}


def main() -> int:
    tracked = subprocess.check_output(["git", "ls-files", "-z", "*.md"], cwd=ROOT).split(b"\0")
    files = {ROOT / item.decode("utf-8") for item in tracked if item}
    files.update((ROOT / "docs").glob("*.md"))
    files.discard(ROOT / "LINKS.md")
    references = set(EXTRA)
    for path in sorted(files):
        if not path.is_file() or path.is_symlink() or path.stat().st_size > 512 * 1024:
            continue
        for value in re.findall(r"https://[^\s<>\)\]\"`]+", path.read_text(encoding="utf-8")):
            value = value.rstrip(".,;")
            parsed = urlsplit(value)
            # Never turn credential-bearing or signed/query URLs into a public index.
            if parsed.hostname and not parsed.username and not parsed.password and not parsed.query:
                references.add(value)
    lines = ["# CloudSentry source, creator and guide index", "",
             "All entries are documented public references or local source guides, not endorsements, installed components or automatic integrations. Upstream work and licenses remain with their creators. See the root README's creator credits and the configuration auditor's preserved upstream license and source pin.", "",
             "## Guides and source on main", ""]
    for path in sorted(files):
        if path.is_file() and not path.is_symlink():
            relative = path.relative_to(ROOT).as_posix()
            lines.append(f"- [{relative}]({relative.replace(' ', '%20')})")
    lines += ["", "## Public project and documentation references", ""]
    for value in sorted(references):
        safe = value.replace("(", "%28").replace(")", "%29")
        lines.append(f"- [{safe}]({safe})")
    lines += ["", "This index is generated by `python3 scripts/update-links.py`. It does not download, vendor, execute, contact, or authorize any linked project. Historical documentation can describe earlier stages; read current limitations beside each feature.", ""]
    (ROOT / "LINKS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Indexed {len(files)} guides and {len(references)} public references.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
